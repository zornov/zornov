//! Regenerates Studio's shipped looks (`crates/picture/colour/looks/*.cube`) from
//! the grade parameters in `studio_colour::looks`.
//!
//! Run: `cargo run -p studio-colour --example gen_looks`

use studio_colour::looks::{LOOK_SIZE, LOOKS};
use studio_colour::lut::write_cube;

fn main() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("looks");
    std::fs::create_dir_all(&dir).expect("create looks dir");
    for look in LOOKS {
        let lut = look.bake(LOOK_SIZE);
        let path = dir.join(format!("{}.cube", look.slug));
        let text = format!(
            "# Studio look \"{}\", generated by examples/gen_looks.rs from src/looks.rs.\n\
             # Input and output: BT.709 primaries, BT.1886 (2.4 gamma) encoded.\n{}",
            look.title,
            write_cube(&lut, look.title)
        );
        std::fs::write(&path, text).expect("write cube");
        println!("wrote {}", path.display());
    }
}
