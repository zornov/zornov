/// A prefix code as (length, value).
#[derive(Clone, Copy, Default, Debug)]
pub struct Code {
    pub len: u8,
    pub bits: u16,
}

pub fn code(s: &str) -> Code {
    if s.is_empty() {
        return Code::default();
    }
    Code { len: s.len() as u8, bits: u16::from_str_radix(s, 2).expect("binary") }
}

/// Lookup-friendly CAVLC tables.
pub struct VlcTables {
    /// [table 0..=4][TotalCoeff][TrailingOnes]
    pub coeff_token: [[[Code; 4]; 17]; 5],
    pub total_zeros_4x4: [[Code; 16]; 15],
    pub total_zeros_2x2: [[Code; 4]; 3],
    pub run_before: [[Code; 15]; 7],
}

pub fn vlc_tables() -> &'static VlcTables {
    static T: std::sync::OnceLock<VlcTables> = std::sync::OnceLock::new();
    T.get_or_init(|| {
        let mut t = VlcTables {
            coeff_token: [[[Code::default(); 4]; 17]; 5],
            total_zeros_4x4: [[Code::default(); 16]; 15],
            total_zeros_2x2: [[Code::default(); 4]; 3],
            run_before: [[Code::default(); 15]; 7],
        };
        for &(t1, tc, ref s) in COEFF_TOKEN.iter() {
            for (k, s) in s.iter().enumerate() {
                t.coeff_token[k][tc as usize][t1 as usize] = code(s);
            }
        }
        for (i, row) in TOTAL_ZEROS_4X4.iter().enumerate() {
            for (j, s) in row.iter().enumerate() {
                t.total_zeros_4x4[i][j] = code(s);
            }
        }
        for (i, row) in TOTAL_ZEROS_2X2.iter().enumerate() {
            for (j, s) in row.iter().enumerate() {
                t.total_zeros_2x2[i][j] = code(s);
            }
        }
        for (i, row) in RUN_BEFORE.iter().enumerate() {
            for (j, s) in row.iter().enumerate() {
                t.run_before[i][j] = code(s);
            }
        }
        t
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cbp_tables_are_permutations() {
        let mut a = CBP_INTRA.to_vec();
        a.sort();
        assert_eq!(a, (0..48).collect::<Vec<u8>>());
        let mut b = CBP_INTER.to_vec();
        b.sort();
        assert_eq!(b, (0..48).collect::<Vec<u8>>());
        for c in 0..48u8 {
            assert_eq!(CBP_INTRA[cbp_code_intra(c) as usize], c);
            assert_eq!(CBP_INTER[cbp_code_inter(c) as usize], c);
        }
    }

    #[test]
    fn mf_times_v_is_two_to_the_17ish() {
        // MF * V ~= 2^21 / normalisation for each class.
        for m in 0..6 {
            let p0 = MF4[m][0] as f64 * V4[m][0] as f64;
            assert!((p0 / 131072.0 - 1.0).abs() < 0.01, "{m}");
        }
    }
}
