/// Position class of raster position `pos` in a 4x4 block: 0 = both even, 1 = both odd, 2 = mixed.
pub const fn pos_class(pos: usize) -> usize {
    let (i, j) = (pos / 4, pos % 4);
    if i % 2 == 0 && j % 2 == 0 {
        0
    } else if i % 2 == 1 && j % 2 == 1 {
        1
    } else {
        2
    }
}

/// LevelScale4x4 with flat weights (16 * v).
pub fn level_scale(m: usize, pos: usize) -> i32 {
    16 * V4[m][pos_class(pos)]
}

