//! Between `studio-model` and the UI's [`view`](crate::view) structs.
//!
//! * [`view_of`] projects a model project into the plain view the screens
//!   draw from (values evaluated at a time, so keyframed properties show
//!   their animated value).
//! * [`diff`] turns "the view before" and "the view after" a UI change into
//!   model [`Edit`](m::Edit)s, so simple attribute changes can be written as
//!   closures over the view while the model stays the only source of truth.
//!   Structural operations (split, trim, move, ripple delete, …) do not go
//!   through here; the editor sends the model's own operations for those.
//! * [`to_model`] builds a model project from a view (used for the sample
//!   projects).
//!
//! The UI shows friendly ranges (−100..100 for grade sliders, percent for
//! scale and opacity); the model stores the units `colour` and `render`
//! use (stops, kelvin, fractions). The conversions live here.

use crate::view::{self, ClipKind, LaneKind, MediaKind, SEC, Time};
use eframe::egui::Color32;
use std::collections::{BTreeMap, HashMap};
use studio_model as m;

/// Media items generated by the app (no file on disk) keep their picture
/// seed here.
pub const SEED_KEY: &str = "studio_app_seed";
/// In/out range of the active sequence, kept in the project settings so it
/// is saved and undoable.
pub const RANGE_KEY: &str = "studio_app_range";
/// Lane height in the timeline.
pub const HEIGHT_KEY: &str = "studio_app_height";
/// Display name of a sample asset shape.
pub const SHAPE_KEY: &str = "shape";

const NEUTRAL_K: f64 = 6504.0;

// --- value conversions ---------------------------------------------------

/// UI value (as shown in the Inspector) for a model property value.
pub fn ui_value(path: &str, v: &m::Value) -> f32 {
    let x = match v {
        m::Value::Scalar(x) | m::Value::Angle(x) => *x,
        m::Value::Bool(b) => *b as u8 as f64,
        _ => 0.0,
    };
    (match path {
        "transform.scale_x" | "transform.scale_y" | "transform.opacity" => x * 100.0,
        "audio.pan" => x * 100.0,
        "grade.exposure" => x * 25.0,
        "grade.temperature" => (x.max(1000.0) / NEUTRAL_K).log2() / 0.8 * 100.0,
        "grade.saturation" => (x - 1.0) * 100.0,
        "grade.contrast" | "grade.tint" => x * 100.0,
        _ => x,
    }) as f32
}

/// Model property value for a UI value.
pub fn model_value(path: &str, ui: f32) -> m::Value {
    let u = ui as f64;
    match path {
        "transform.rotation" => m::Value::Angle(u),
        "transform.scale_x" | "transform.scale_y" | "transform.opacity" | "audio.pan" => m::Value::Scalar(u / 100.0),
        "grade.exposure" => m::Value::Scalar(u / 25.0),
        "grade.temperature" => m::Value::Scalar(NEUTRAL_K * (0.8 * u / 100.0).exp2()),
        "grade.saturation" => m::Value::Scalar(1.0 + u / 100.0),
        "grade.contrast" | "grade.tint" => m::Value::Scalar(u / 100.0),
        _ => m::Value::Scalar(u),
    }
}

/// The grade parameters the view exposes, as (view field, model path).
pub const GRADE_PARAMS: [&str; 5] = ["exposure", "contrast", "saturation", "temperature", "tint"];

/// The blend modes the Inspector offers, in menu order (the first five keep
/// the numbers older projects saved); the track mattes have their own row.
pub const BLENDS: [(m::BlendMode, &str); 17] = [
    (m::BlendMode::Normal, "Normal"),
    (m::BlendMode::Multiply, "Multiply"),
    (m::BlendMode::Screen, "Screen"),
    (m::BlendMode::Overlay, "Overlay"),
    (m::BlendMode::Add, "Add"),
    (m::BlendMode::SoftLight, "Soft light"),
    (m::BlendMode::HardLight, "Hard light"),
    (m::BlendMode::ColourDodge, "Colour dodge"),
    (m::BlendMode::ColourBurn, "Colour burn"),
    (m::BlendMode::Darken, "Darken"),
    (m::BlendMode::Lighten, "Lighten"),
    (m::BlendMode::Difference, "Difference"),
    (m::BlendMode::Exclusion, "Exclusion"),
    (m::BlendMode::Hue, "Hue"),
    (m::BlendMode::Saturation, "Saturation"),
    (m::BlendMode::Colour, "Colour"),
    (m::BlendMode::Luminosity, "Luminosity"),
];

pub(crate) fn rgba(c: Color32) -> m::Rgba {
    let [r, g, b, a] = c.to_srgba_unmultiplied();
    m::Rgba { r: r as f64 / 255.0, g: g as f64 / 255.0, b: b as f64 / 255.0, a: a as f64 / 255.0 }
}

pub(crate) fn color32(c: &m::Rgba) -> Color32 {
    let q = |v: f64| (v.clamp(0.0, 1.0) * 255.0).round() as u8;
    Color32::from_rgba_unmultiplied(q(c.r), q(c.g), q(c.b), q(c.a))
}

fn fps_of(r: m::FrameRate) -> f32 {
    r.as_f64() as f32
}

fn rate_of(fps: f32) -> m::FrameRate {
    match fps {
        x if (x - 29.97).abs() < 0.01 => m::FrameRate { num: 30000, den: 1001 },
        x if (x - 59.94).abs() < 0.01 => m::FrameRate { num: 60000, den: 1001 },
        x if (x - 23.976).abs() < 0.01 => m::FrameRate { num: 24000, den: 1001 },
        x => m::FrameRate { num: x.round().max(1.0) as u32, den: 1 },
    }
}

fn scalar(map: &m::ParamMap, key: &str) -> Option<f64> {
    map.get(key).and_then(|v| v.as_f64())
}

// --- model → view --------------------------------------------------------

/// Project the active sequence of `p` at sequence time `time`.
pub fn view_of(p: &m::Project, time: Time) -> view::Project {
    let seq = p.active();
    let media: Vec<view::MediaItem> = p.media.iter().map(media_view).collect();
    let lanes: Vec<view::Lane> = seq.lanes.iter().map(lane_view).collect();
    let mut clips = Vec::with_capacity(seq.clips.len());
    for c in &seq.clips {
        if c.is_gap() {
            continue;
        }
        if let Some(v) = clip_view(p, c, time) {
            clips.push(v);
        }
    }
    let range = p.settings.extra.get(RANGE_KEY).and_then(|v| {
        let a = v.get(0)?.as_i64()?;
        let b = v.get(1)?.as_i64()?;
        (b > a).then_some((a, b))
    });
    view::Project {
        name: seq.name.clone(),
        width: p.settings.width,
        height: p.settings.height,
        fps: fps_of(p.settings.frame_rate),
        background: color32(&p.settings.background),
        lanes,
        clips,
        transitions: seq
            .transitions
            .iter()
            .map(|t| view::Transition { id: t.id.0, left: t.left.0 as u32, right: t.right.0 as u32, dur: t.duration, kind: t.kind.clone() })
            .collect(),
        markers: seq.markers.iter().map(|mk| view::Marker { id: mk.id.0, time: mk.time, note: if mk.note.is_empty() { mk.name.clone() } else { mk.note.clone() } }).collect(),
        media,
        range,
        next_id: p.next_id as u32,
    }
}

fn media_view(mi: &m::MediaItem) -> view::MediaItem {
    let kind = match mi.info.kind {
        m::MediaKind::Video => MediaKind::Video,
        m::MediaKind::Audio => MediaKind::Audio,
        m::MediaKind::Image => MediaKind::Image,
    };
    let (width, height, fps) = mi.info.video.as_ref().map_or((0, 0, 30.0), |v| (v.width, v.height, v.frame_rate.map_or(30.0, fps_of)));
    // Generated footage keeps its seed; real files get one from their path
    // so their placeholder thumbnail is stable.
    let seed = mi.extra.get(SEED_KEY).and_then(|v| v.as_u64()).map(|s| s as u32).unwrap_or_else(|| {
        mi.path.bytes().fold(17u32, |h, b| h.wrapping_mul(31).wrapping_add(b as u32))
    });
    let path = (!mi.path.starts_with("sample:")).then(|| std::path::PathBuf::from(&mi.path));
    view::MediaItem { id: mi.id.0 as u32, name: mi.name.clone(), kind, dur: mi.info.duration.unwrap_or(5 * SEC), width, height, fps, seed, path }
}

fn lane_view(l: &m::Lane) -> view::Lane {
    let kind = match l.kind {
        m::LaneKind::Spine => LaneKind::Spine,
        m::LaneKind::Visual => LaneKind::Visual,
        m::LaneKind::Audio => LaneKind::Audio,
    };
    let default_h = match kind {
        LaneKind::Spine => 52.0,
        LaneKind::Visual => 36.0,
        LaneKind::Audio => 40.0,
    };
    let fallback = match kind {
        LaneKind::Spine => Color32::from_rgb(0x8B, 0x6C, 0xFF),
        LaneKind::Visual => Color32::from_rgb(0x7F, 0xA8, 0xE8),
        LaneKind::Audio => Color32::from_rgb(0x6C, 0xC6, 0xA0),
    };
    view::Lane {
        id: l.id.0 as u32,
        name: l.name.clone(),
        kind,
        locked: l.locked,
        hidden: l.hidden,
        muted: l.muted,
        solo: l.solo,
        height: l.extra.get(HEIGHT_KEY).and_then(|v| v.as_f64()).map_or(default_h, |h| h as f32),
        colour: l.colour.as_ref().map_or(fallback, color32),
    }
}

pub fn clip_view(p: &m::Project, c: &m::Clip, time: Time) -> Option<view::Clip> {
    let local = (time - c.start).clamp(0, c.duration.max(0));
    let (kind, media, text, text_colour) = match &c.source {
        m::ClipSource::Media(r) => {
            let audio_only = !r.video || p.media_item(r.media).is_some_and(|mi| mi.info.kind == m::MediaKind::Audio);
            (if audio_only { ClipKind::Audio } else { ClipKind::Video }, Some(r.media.0 as u32), String::new(), Color32::WHITE)
        }
        m::ClipSource::Generator(g) => {
            let colour = g.params.get("colour").and_then(|v| if let m::Value::Colour(c) = v { Some(color32(c)) } else { None }).unwrap_or(Color32::WHITE);
            match g.kind {
                m::GeneratorKind::Adjustment | m::GeneratorKind::Camera | m::GeneratorKind::Light => (ClipKind::Fx, None, String::new(), colour),
                _ => (ClipKind::Title, None, g.plain_text(), colour),
            }
        }
        m::ClipSource::Sequence(_) => (ClipKind::Video, None, String::new(), Color32::WHITE),
        m::ClipSource::Gap => return None,
    };
    let tr = c.transform_at(local);
    let grade_params = c.grade_params_at(local);
    let mut grade = view::Grade { enabled: c.grade.as_ref().is_none_or(|g| g.enabled), ..Default::default() };
    for name in GRADE_PARAMS {
        if let Some(v) = grade_params.get(name) {
            let ui = ui_value(&format!("grade.{name}"), v);
            match name {
                "exposure" => grade.exposure = ui,
                "contrast" => grade.contrast = ui,
                "saturation" => grade.saturation = ui,
                "temperature" => grade.temperature = ui,
                _ => grade.tint = ui,
            }
        }
    }
    let look = grade_params.get("look").and_then(|v| if let m::Value::Choice(s) | m::Value::Text(s) = v { Some(s.clone()) } else { None });
    let vol = c.property_at("audio.volume_db", local).and_then(|v| v.as_f64()).unwrap_or(c.audio.volume_db);
    let pan = c.property_at("audio.pan", local).and_then(|v| v.as_f64()).unwrap_or(c.audio.pan);
    let speed = match &c.speed {
        m::Speed::Constant(r) => *r as f32 * 100.0,
        s => s.rate_at(local) as f32 * 100.0,
    };
    let effects = c
        .effects
        .iter()
        .map(|e| {
            let params = c.effect_params_at(e, local).iter().filter_map(|(k, v)| v.as_f64().map(|x| (k.clone(), x as f32))).collect();
            view::Effect { id: e.id.0, kind: e.kind.clone(), enabled: e.enabled, params }
        })
        .collect();
    let mask = c.masks.first();
    let gen_params = if let m::ClipSource::Generator(g) = &c.source { Some(&g.params) } else { None };
    let align = gen_params.and_then(|p| p.get("align")).and_then(|v| if let m::Value::Choice(s) = v { Some(s.as_str()) } else { None });
    Some(view::Clip {
        id: c.id.0 as u32,
        lane: c.lane.0 as u32,
        start: c.start,
        dur: c.duration,
        src_in: c.source_in,
        kind,
        name: c.name.clone(),
        media,
        text,
        text_colour,
        transform: view::Transform {
            x: tr.position.x as f32,
            y: tr.position.y as f32,
            scale: (tr.scale_x * 100.0) as f32,
            rotation: tr.rotation as f32,
            opacity: (tr.opacity * 100.0) as f32,
        },
        grade,
        audio: view::AudioParams {
            enabled: !c.audio.muted,
            volume: vol as f32,
            pan: (pan * 100.0) as f32,
            fade_in: c.audio.fade_in.duration as f32 / SEC as f32,
            fade_out: c.audio.fade_out.duration as f32 / SEC as f32,
        },
        speed,
        effects,
        motion_in: c.motion.entry.as_ref().map(|m| m.kind.clone()),
        look,
        keys: c.keyframes.iter().map(|(k, tr)| (k.clone(), tr.keys.iter().map(|k| k.time).collect())).collect(),
        text_style: gen_params.and_then(|p| p.get("style")).and_then(|v| if let m::Value::Choice(s) = v { Some(s.clone()) } else { None }),
        extra: view::Extra {
            mask: mask.map_or(0, |mk| match mk.shape {
                m::MaskShape::Rectangle => 1,
                m::MaskShape::Ellipse => 2,
                _ => 3,
            }),
            feather: mask.and_then(|mk| scalar(&mk.params, "feather")).unwrap_or(0.0) as f32,
            mask_invert: mask.is_some_and(|mk| mk.invert),
            crop: [tr.crop.left as f32, tr.crop.right as f32, tr.crop.top as f32, tr.crop.bottom as f32],
            flip: tr.flip_x,
            reverse: c.reversed,
            text_size: gen_params.and_then(|p| scalar(p, "size")).unwrap_or(40.0) as f32,
            letter_spacing: gen_params.and_then(|p| scalar(p, "letter_spacing")).unwrap_or(0.0) as f32,
            motion_dur: c.motion.entry.as_ref().map_or(0.5, |m| m.duration as f32 / SEC as f32),
            text_align: match align {
                Some("left") => 0,
                Some("right") => 2,
                _ => 1,
            },
            blend: BLENDS.iter().position(|b| b.0 == c.blend).unwrap_or(0) as u8,
        },
    })
}

// --- view → model --------------------------------------------------------

/// Write a view clip's attributes onto a model clip. Timing, lane and
/// source are written too; keyframed properties are left alone (see
/// [`keyframe_edits`]).
pub fn write_clip(c: &mut m::Clip, v: &view::Clip, before: Option<&view::Clip>) {
    let keyed = |path: &str| c.keyframes.contains_key(path);
    c.lane = m::LaneId(v.lane as u64);
    c.start = v.start;
    c.duration = v.dur;
    c.source_in = v.src_in;
    c.name = v.name.clone();
    let changed = |f: fn(&view::Clip) -> f32| before.is_none_or(|b| f(b) != f(v));
    let t = &mut c.transform;
    if !c.keyframes.contains_key("transform.position") && (changed(|c| c.transform.x) || changed(|c| c.transform.y)) {
        t.position = m::Vec2 { x: v.transform.x as f64, y: v.transform.y as f64 };
    }
    if !keyed("transform.scale_x") && changed(|c| c.transform.scale) {
        t.scale_x = v.transform.scale as f64 / 100.0;
        t.scale_y = v.transform.scale as f64 / 100.0;
    }
    if !keyed("transform.rotation") && changed(|c| c.transform.rotation) {
        t.rotation = v.transform.rotation as f64;
    }
    if !keyed("transform.opacity") && changed(|c| c.transform.opacity) {
        t.opacity = v.transform.opacity as f64 / 100.0;
    }
    let t = &mut c.transform;
    t.flip_x = v.extra.flip;
    c.reversed = v.extra.reverse;
    // Only when the Inspector changed it: the track mattes are not in the
    // view and must survive an edit.
    if changed(|c| c.extra.blend as f32) {
        c.blend = BLENDS.get(v.extra.blend as usize).map_or(m::BlendMode::Normal, |b| b.0);
    }

    // Audio.
    c.audio.muted = !v.audio.enabled;
    if !keyed("audio.volume_db") && changed(|c| c.audio.volume) {
        c.audio.volume_db = v.audio.volume as f64;
    }
    if !keyed("audio.pan") && changed(|c| c.audio.pan) {
        c.audio.pan = v.audio.pan as f64 / 100.0;
    }
    c.audio.fade_in.duration = (v.audio.fade_in as f64 * SEC as f64) as Time;
    c.audio.fade_out.duration = (v.audio.fade_out as f64 * SEC as f64) as Time;

    // Grade: present only when something is set.
    let g = &v.grade;
    let any = g.exposure != 0.0 || g.contrast != 0.0 || g.saturation != 0.0 || g.temperature != 0.0 || g.tint != 0.0 || v.look.is_some() || !g.enabled;
    if any || c.grade.is_some() {
        let mut grade = c.grade.clone().unwrap_or(m::Grade { enabled: true, params: Default::default(), lut: None, extra: Default::default() });
        grade.enabled = g.enabled;
        for (name, val) in [("exposure", g.exposure), ("contrast", g.contrast), ("saturation", g.saturation), ("temperature", g.temperature), ("tint", g.tint)] {
            let path = format!("grade.{name}");
            if keyed(&path) {
                continue;
            }
            if val == 0.0 {
                grade.params.remove(name);
            } else {
                grade.params.insert(name.into(), model_value(&path, val));
            }
        }
        match &v.look {
            Some(l) => {
                grade.params.insert("look".into(), m::Value::Choice(l.clone()));
            }
            None => {
                grade.params.remove("look");
            }
        }
        c.grade = (any || !grade.params.is_empty()).then_some(grade);
    }

    // Text generators (cameras and lights keep their own settings).
    if let m::ClipSource::Generator(gen_) = &mut c.source
        && !matches!(gen_.kind, m::GeneratorKind::Camera | m::GeneratorKind::Light)
    {
        if gen_.kind == m::GeneratorKind::Text && gen_.plain_text() != v.text {
            let style = gen_.text.first().map(|r| r.style.clone()).unwrap_or_default();
            gen_.text = vec![m::TextRun { text: v.text.clone(), style }];
        }
        gen_.params.insert("colour".into(), m::Value::Colour(rgba(v.text_colour)));
        // Shapes paint with "fill": a colour picked for the clip (anything
        // but the default white) is that fill.
        if gen_.kind == m::GeneratorKind::Shape && v.text_colour != eframe::egui::Color32::WHITE {
            gen_.params.insert("fill".into(), m::Value::Colour(rgba(v.text_colour)));
        }
        gen_.params.insert("align".into(), m::Value::Choice(["left", "centre", "right"][v.extra.text_align.min(2) as usize].into()));
        if gen_.kind == m::GeneratorKind::Text {
            match &v.text_style {
                Some(id) => gen_.params.insert("style".into(), m::Value::Choice(id.clone())),
                None => gen_.params.remove("style"),
            };
            gen_.params.insert("size".into(), m::Value::Scalar(v.extra.text_size as f64));
            gen_.params.insert("letter_spacing".into(), m::Value::Scalar(v.extra.letter_spacing as f64));
        }
    }

    // Motion.
    match (&v.motion_in, &mut c.motion.entry) {
        (None, e) => *e = None,
        (Some(k), Some(e)) if e.kind == *k => e.duration = (v.extra.motion_dur as f64 * SEC as f64) as Time,
        (Some(k), e) => *e = Some(m::MotionPreset { kind: k.clone(), duration: (v.extra.motion_dur as f64 * SEC as f64) as Time, params: Default::default() }),
    }

    // Effects: match by id; new ones (id 0) were given ids by the caller.
    let mut out = Vec::with_capacity(v.effects.len());
    for ve in &v.effects {
        let mut e = c.effects.iter().find(|e| e.id.0 == ve.id).cloned().unwrap_or_else(|| m::Effect::new(m::EffectId(ve.id), ve.kind.clone()));
        e.enabled = ve.enabled;
        for (k, val) in &ve.params {
            if !c.keyframes.contains_key(&format!("effect.{}.{k}", ve.id)) {
                e.params.insert(k.clone(), m::Value::Scalar(*val as f64));
            }
        }
        out.push(e);
    }
    c.effects = out;

    // Masks: one simple shape from the Inspector.
    match v.extra.mask {
        0 => c.masks.clear(),
        shape => {
            let shape = match shape {
                1 => m::MaskShape::Rectangle,
                2 => m::MaskShape::Ellipse,
                _ => m::MaskShape::Path,
            };
            let id = c.masks.first().map_or(m::MaskId(c.id.0 * 1000 + 1), |mk| mk.id);
            let mut mk = c.masks.first().cloned().unwrap_or_else(|| m::Mask::new(id, shape));
            mk.shape = shape;
            mk.invert = v.extra.mask_invert;
            mk.params.insert("feather".into(), m::Value::Scalar(v.extra.feather as f64));
            c.masks = vec![mk];
        }
    }
}

/// For properties that have keyframes, a change in the view becomes a key
/// at the current time instead of a new static value.
pub fn keyframe_edits(seq: m::SequenceId, c: &m::Clip, before: &view::Clip, after: &view::Clip, time: Time) -> Vec<m::Edit> {
    let local = (time - c.start).clamp(0, c.duration.max(0));
    let mut out = Vec::new();
    let mut key = |path: &str, value: m::Value| {
        if c.keyframes.contains_key(path) {
            out.push(m::Edit::SetKeyframe { seq, clip: c.id, property: path.into(), key: m::Keyframe::new(local, value, m::Interp::default()) });
        }
    };
    let (b, a) = (&before.transform, &after.transform);
    if (b.x, b.y) != (a.x, a.y) {
        key("transform.position", m::Value::Point(m::Vec2 { x: a.x as f64, y: a.y as f64 }));
    }
    if b.scale != a.scale {
        key("transform.scale_x", model_value("transform.scale_x", a.scale));
        key("transform.scale_y", model_value("transform.scale_y", a.scale));
    }
    if b.rotation != a.rotation {
        key("transform.rotation", model_value("transform.rotation", a.rotation));
    }
    if b.opacity != a.opacity {
        key("transform.opacity", model_value("transform.opacity", a.opacity));
    }
    if before.audio.volume != after.audio.volume {
        key("audio.volume_db", m::Value::Scalar(after.audio.volume as f64));
    }
    if before.audio.pan != after.audio.pan {
        key("audio.pan", model_value("audio.pan", after.audio.pan));
    }
    let gb = &before.grade;
    let ga = &after.grade;
    for (name, x, y) in [("exposure", gb.exposure, ga.exposure), ("contrast", gb.contrast, ga.contrast), ("saturation", gb.saturation, ga.saturation), ("temperature", gb.temperature, ga.temperature), ("tint", gb.tint, ga.tint)] {
        if x != y {
            let path = format!("grade.{name}");
            key(&path, model_value(&path, y));
        }
    }
    out
}

/// Parameters for the sample asset shapes, in `render`'s shape generator
/// terms (shape, fill, stroke, size as fractions of the picture, …).
fn shape_params(name: &str, p: &mut m::ParamMap) {
    let colour = |r: f64, g: f64, b: f64| m::Value::Colour(m::Rgba { r, g, b, a: 1.0 });
    let (shape, fill, extra): (&str, m::Value, Vec<(&str, m::Value)>) = match name {
        "Circle" => ("ellipse", colour(1.0, 0.78, 0.34), vec![]),
        "Rounded box" => ("rectangle", colour(0.5, 0.82, 0.73), vec![("roundness", m::Value::Scalar(0.3))]),
        "Arrow" => ("arrow", colour(0.95, 0.42, 0.36), vec![]),
        "Star" => ("star", colour(0.55, 0.42, 1.0), vec![("sides", m::Value::Scalar(5.0))]),
        "Burst" => ("star", colour(0.95, 0.42, 0.36), vec![("sides", m::Value::Scalar(12.0))]),
        "Spark" => ("star", colour(1.0, 0.78, 0.34), vec![("sides", m::Value::Scalar(4.0))]),
        "Underline" => ("line", colour(0.5, 0.82, 0.73), vec![]),
        "Ring" => ("ellipse", m::Value::Colour(m::Rgba { r: 0.0, g: 0.0, b: 0.0, a: 0.0 }), vec![("stroke", colour(0.44, 0.66, 1.0)), ("stroke_width", m::Value::Scalar(0.06))]),
        "Badge" => ("polygon", colour(0.55, 0.42, 1.0), vec![("sides", m::Value::Scalar(8.0))]),
        _ => ("rectangle", colour(0.44, 0.66, 1.0), vec![("roundness", m::Value::Scalar(0.15))]),
    };
    p.insert(SHAPE_KEY.into(), m::Value::Choice(shape.into()));
    p.insert("fill".into(), fill);
    // Square on a 16:9 canvas: half the height wide and tall.
    p.insert("size".into(), m::Value::Point(m::Vec2 { x: 0.28125, y: 0.5 }));
    for (k, v) in extra {
        p.insert(k.into(), v);
    }
}

/// A new model clip for a view clip (sources: media, text, shape or
/// adjustment generator).
pub fn new_clip(p: &m::Project, v: &view::Clip) -> m::Clip {
    let source = match (v.kind, v.media) {
        (ClipKind::Video | ClipKind::Audio, Some(mid)) => {
            let audio_only = v.kind == ClipKind::Audio;
            let has_audio = p.media_item(m::MediaId(mid as u64)).is_none_or(|mi| mi.info.audio.is_some() || mi.info.kind == m::MediaKind::Audio);
            m::ClipSource::Media(m::MediaRef { media: m::MediaId(mid as u64), video: !audio_only, audio: audio_only || has_audio, extra: Default::default() })
        }
        (ClipKind::Fx, _) => m::ClipSource::Generator(m::Generator::new(m::GeneratorKind::Adjustment)),
        (ClipKind::Title, _) if v.text.is_empty() => {
            let mut g = m::Generator::new(m::GeneratorKind::Shape);
            shape_params(&v.name, &mut g.params);
            m::ClipSource::Generator(g)
        }
        _ => m::ClipSource::Generator(m::Generator::text(v.text.clone())),
    };
    let mut c = m::Clip::new(m::ClipId(v.id as u64), m::LaneId(v.lane as u64), v.start, v.dur, source);
    c.speed = m::Speed::Constant(v.speed as f64 / 100.0);
    write_clip(&mut c, v, None);
    c
}

fn new_lane(v: &view::Lane) -> m::Lane {
    let kind = match v.kind {
        LaneKind::Spine => m::LaneKind::Spine,
        LaneKind::Visual => m::LaneKind::Visual,
        LaneKind::Audio => m::LaneKind::Audio,
    };
    let mut l = m::Lane::new(m::LaneId(v.id as u64), kind, v.name.clone());
    write_lane(&mut l, v);
    l
}

fn write_lane(l: &mut m::Lane, v: &view::Lane) {
    l.name = v.name.clone();
    l.locked = v.locked;
    l.hidden = v.hidden;
    l.muted = v.muted;
    l.solo = v.solo;
    l.colour = Some(rgba(v.colour));
    l.extra.insert(HEIGHT_KEY.into(), serde_json::json!(v.height));
}

fn new_media(v: &view::MediaItem) -> m::MediaItem {
    let kind = match v.kind {
        MediaKind::Video => m::MediaKind::Video,
        MediaKind::Audio => m::MediaKind::Audio,
        MediaKind::Image => m::MediaKind::Image,
    };
    let video = (v.kind != MediaKind::Audio).then(|| m::VideoInfo {
        codec: if v.kind == MediaKind::Image { "png".into() } else { "h264".into() },
        width: v.width,
        height: v.height,
        frame_rate: (v.kind == MediaKind::Video).then(|| rate_of(v.fps)),
        rotation: 0,
        has_alpha: false,
        colour: Default::default(),
    });
    let audio = (v.kind != MediaKind::Image).then(|| m::AudioInfo { codec: "aac".into(), sample_rate: 48_000, channels: 2, ..Default::default() });
    let info = m::MediaInfo {
        kind,
        container: "mp4".into(),
        duration: (v.kind != MediaKind::Image).then_some(v.dur),
        video,
        audio,
        extra: Default::default(),
    };
    let path = v.path.as_ref().map_or_else(|| format!("sample:{}", v.name), |p| p.display().to_string());
    let mut mi = m::MediaItem::new(m::MediaId(v.id as u64), path, info);
    mi.name = v.name.clone();
    mi.extra.insert(SEED_KEY.into(), serde_json::json!(v.seed));
    mi
}

fn settings_of(p: &m::Project, v: &view::Project) -> m::ProjectSettings {
    let mut s = p.settings.clone();
    s.width = v.width;
    s.height = v.height;
    s.frame_rate = rate_of(v.fps);
    s.background = rgba(v.background);
    match v.range {
        Some((a, b)) => {
            s.extra.insert(RANGE_KEY.into(), serde_json::json!([a, b]));
        }
        None => {
            s.extra.remove(RANGE_KEY);
        }
    }
    s
}

/// Model edits that take the project from `before` to `after` (both views
/// of `p`'s active sequence at `time`). New objects in `after` must already
/// carry ids from `p.alloc_id()`.
pub fn diff(p: &m::Project, before: &view::Project, after: &view::Project, time: Time) -> Vec<m::Edit> {
    let seq = p.active_sequence;
    let model_seq = p.active();
    let mut edits = Vec::new();

    if before.width != after.width || before.height != after.height || before.fps != after.fps || before.background != after.background || before.range != after.range {
        edits.push(m::Edit::SetSettings { settings: Box::new(settings_of(p, after)) });
    }
    if before.name != after.name {
        edits.push(m::Edit::RenameSequence { id: seq, name: after.name.clone() });
    }

    // Media.
    let old_media: HashMap<u32, &view::MediaItem> = before.media.iter().map(|x| (x.id, x)).collect();
    for mi in &after.media {
        if !old_media.contains_key(&mi.id) {
            edits.push(m::Edit::InsertMedia { item: Box::new(new_media(mi)), index: None });
        }
    }
    let new_media_ids: std::collections::HashSet<u32> = after.media.iter().map(|x| x.id).collect();
    for mi in &before.media {
        if !new_media_ids.contains(&mi.id) {
            edits.push(m::Edit::RemoveMedia { id: m::MediaId(mi.id as u64) });
        }
    }

    // Lanes.
    let old_lanes: HashMap<u32, &view::Lane> = before.lanes.iter().map(|x| (x.id, x)).collect();
    for (i, l) in after.lanes.iter().enumerate() {
        match old_lanes.get(&l.id) {
            None => edits.push(m::Edit::InsertLane { seq, index: i, lane: new_lane(l) }),
            Some(o) if *o != l => {
                let mut ml = model_seq.lane(m::LaneId(l.id as u64)).cloned().unwrap_or_else(|| new_lane(l));
                write_lane(&mut ml, l);
                edits.push(m::Edit::SetLane { seq, lane: ml });
            }
            _ => {}
        }
    }

    // Clips: removals, then changes, then insertions. Usually the same
    // clips in the same order with a few changed: compared in step, with
    // no maps of every clip (milliseconds per edit on a long project).
    let same_order = before.clips.len() == after.clips.len() && before.clips.iter().zip(&after.clips).all(|(a, b)| a.id == b.id);
    let mut pairs: Vec<(Option<&view::Clip>, &view::Clip)> = Vec::new();
    if same_order {
        pairs.extend(before.clips.iter().zip(&after.clips).filter(|(o, c)| o != c).map(|(o, c)| (Some(o), c)));
    } else {
        let old_clips: HashMap<u32, &view::Clip> = before.clips.iter().map(|x| (x.id, x)).collect();
        let new_ids: std::collections::HashSet<u32> = after.clips.iter().map(|x| x.id).collect();
        for c in &before.clips {
            if !new_ids.contains(&c.id) {
                edits.push(m::Edit::RemoveClip { seq, clip: m::ClipId(c.id as u64) });
            }
        }
        pairs.extend(after.clips.iter().map(|c| (old_clips.get(&c.id).copied(), c)).filter(|(o, c)| o.is_none_or(|o| o != *c)));
    }
    let mut inserts = Vec::new();
    // By id: a lookup per clip was a scan of every clip (half a second per
    // edit on a long project).
    let model_clips: Option<HashMap<u64, &m::Clip>> = (pairs.len() > 16).then(|| model_seq.clips.iter().map(|c| (c.id.0, c)).collect());
    let model_clip = |id: u32| match &model_clips {
        Some(map) => map.get(&(id as u64)).copied(),
        None => model_seq.clip(m::ClipId(id as u64)),
    };
    for (o, c) in pairs {
        match (o, model_clip(c.id)) {
            (Some(o), Some(mc)) => {
                let mut nc = mc.clone();
                write_clip(&mut nc, c, Some(o));
                if o.speed != c.speed {
                    nc.speed = m::Speed::Constant(c.speed as f64 / 100.0);
                }
                if nc != *mc {
                    edits.push(m::Edit::SetClip { seq, clip: Box::new(nc) });
                }
                edits.extend(keyframe_edits(seq, mc, o, c, time));
            }
            (None, _) => inserts.push(m::Edit::InsertClip { seq, clip: Box::new(new_clip(p, c)) }),
            _ => {}
        }
    }
    edits.extend(inserts);

    // Transitions.
    for t in &before.transitions {
        if !after.transitions.iter().any(|x| x.id == t.id && t.id != 0) {
            edits.push(m::Edit::RemoveTransition { seq, id: m::TransitionId(t.id) });
        }
    }
    for t in &after.transitions {
        let mt = |id: u64| m::Transition {
            id: m::TransitionId(id),
            left: m::ClipId(t.left as u64),
            right: m::ClipId(t.right as u64),
            kind: t.kind.clone(),
            duration: t.dur,
            align: Default::default(),
            params: Default::default(),
            extra: Default::default(),
        };
        match before.transitions.iter().find(|x| x.id == t.id && t.id != 0) {
            None => edits.push(m::Edit::InsertTransition { seq, transition: mt(t.id) }),
            Some(o) if o != t => {
                let mut full = model_seq.transition(m::TransitionId(t.id)).cloned().unwrap_or_else(|| mt(t.id));
                full.kind = t.kind.clone();
                full.duration = t.dur;
                edits.push(m::Edit::SetTransition { seq, transition: full });
            }
            _ => {}
        }
    }

    // Markers.
    for mk in &before.markers {
        if !after.markers.iter().any(|x| x.id == mk.id) {
            edits.push(m::Edit::RemoveMarker { seq, id: m::MarkerId(mk.id) });
        }
    }
    for mk in &after.markers {
        match before.markers.iter().find(|x| x.id == mk.id) {
            None => edits.push(m::Edit::InsertMarker { seq, marker: m::Marker::new(m::MarkerId(mk.id), mk.time, mk.note.clone()) }),
            Some(o) if o != mk => {
                let mut full = model_seq.markers.iter().find(|x| x.id.0 == mk.id).cloned().unwrap_or_else(|| m::Marker::new(m::MarkerId(mk.id), mk.time, mk.note.clone()));
                full.time = mk.time;
                full.name = mk.note.clone();
                edits.push(m::Edit::SetMarker { seq, marker: full });
            }
            _ => {}
        }
    }
    edits
}

/// Build a model project from a sample view. Every object gets a fresh id
/// from the model's counter.
pub fn to_model(v: &view::Project) -> m::Project {
    let mut settings = m::ProjectSettings::default();
    settings.width = v.width;
    settings.height = v.height;
    settings.frame_rate = rate_of(v.fps);
    settings.background = rgba(v.background);
    let mut p = m::Project::new(settings);
    let seq_id = p.active_sequence;

    // Remap ids so lanes, clips and media never share one.
    let mut map: HashMap<(u8, u32), u32> = HashMap::new();
    let mut remap = |p: &mut m::Project, kind: u8, id: u32| *map.entry((kind, id)).or_insert_with(|| p.alloc_id() as u32);
    let mut lanes = Vec::new();
    for l in &v.lanes {
        let mut nl = l.clone();
        nl.id = remap(&mut p, 0, l.id);
        lanes.push(new_lane(&nl));
    }
    let media: Vec<view::MediaItem> = v.media.iter().map(|mi| view::MediaItem { id: remap(&mut p, 1, mi.id), ..mi.clone() }).collect();
    let mut clips = Vec::new();
    for c in &v.clips {
        let mut nc = c.clone();
        nc.id = remap(&mut p, 2, c.id);
        nc.lane = remap(&mut p, 0, c.lane);
        nc.media = c.media.map(|mid| remap(&mut p, 1, mid));
        for e in &mut nc.effects {
            e.id = p.alloc_id();
        }
        clips.push(nc);
    }
    p.media = media.iter().map(new_media).collect();
    let mut model_clips: Vec<m::Clip> = Vec::new();
    for c in &clips {
        let mut mc = new_clip(&p, c);
        for (path, times) in &c.keys {
            let base = mc.get_property(path).unwrap_or(m::Value::Scalar(0.0));
            let keys = times
                .iter()
                .enumerate()
                .map(|(i, t)| {
                    // Sample animation: alternate around the static value.
                    let v = match &base {
                        m::Value::Scalar(x) => m::Value::Scalar(if i % 2 == 0 { *x } else { x - 6.0 }),
                        other => other.clone(),
                    };
                    m::Keyframe::new(*t, v, m::Interp::Ease)
                })
                .collect();
            mc.keyframes.insert(path.clone(), m::Track::new(keys));
        }
        model_clips.push(mc);
    }
    // Pack the spine exactly: sample times come from floats.
    if let Some(spine) = v.lanes.iter().find(|l| l.kind == LaneKind::Spine).and_then(|l| map.get(&(0, l.id))) {
        let mut spine_clips: Vec<&mut m::Clip> = model_clips.iter_mut().filter(|c| c.lane.0 == *spine as u64).collect();
        spine_clips.sort_by_key(|c| c.start);
        let mut t = 0;
        for c in spine_clips {
            c.start = t;
            t += c.duration;
        }
    }
    let seq = &mut p.sequences[0];
    seq.name = v.name.clone();
    seq.lanes = lanes;
    seq.clips = model_clips;
    seq.clips.sort_by_key(|c| (c.lane.0, c.start, c.id.0));
    for t in &v.transitions {
        let id = p.next_id;
        p.next_id += 1;
        let (Some(l), Some(r)) = (map.get(&(2, t.left)), map.get(&(2, t.right))) else { continue };
        p.sequences[0].transitions.push(m::Transition {
            id: m::TransitionId(id),
            left: m::ClipId(*l as u64),
            right: m::ClipId(*r as u64),
            kind: t.kind.clone(),
            duration: t.dur,
            align: Default::default(),
            params: Default::default(),
            extra: Default::default(),
        });
    }
    for mk in &v.markers {
        let id = p.alloc_id();
        p.sequences[0].markers.push(m::Marker::new(m::MarkerId(id), mk.time, mk.note.clone()));
    }
    if let Some((a, b)) = v.range {
        p.settings.extra.insert(RANGE_KEY.into(), serde_json::json!([a, b]));
    }
    let _ = seq_id;
    p
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn samples_convert_and_keep_invariants() {
        for name in ["demo", "empty", "one", "big"] {
            let v = view::by_name(name);
            let p = to_model(&v);
            p.check_invariants().unwrap_or_else(|e| panic!("{name}: {e:?}"));
            let back = view_of(&p, 0);
            assert_eq!(back.clips.len(), v.clips.len(), "{name}");
            assert_eq!(back.lanes.len(), v.lanes.len());
        }
    }

    #[test]
    fn grade_values_round_trip() {
        for (path, ui) in [("grade.exposure", 40.0), ("grade.temperature", -35.0), ("grade.saturation", 12.0), ("transform.opacity", 70.0)] {
            let back = ui_value(path, &model_value(path, ui));
            assert!((back - ui).abs() < 0.01, "{path}: {back}");
        }
    }

    #[test]
    fn attribute_change_round_trips_through_history() {
        let mut p = to_model(&view::demo());
        let mut h = m::History::new();
        let before = view_of(&p, 0);
        let mut after = before.clone();
        let id = after.clips[0].id;
        after.clips[0].transform.opacity = 40.0;
        after.clips[0].grade.exposure = 20.0;
        let edits = diff(&p, &before, &after, 0);
        assert!(!edits.is_empty());
        h.apply(&mut p, "Change", m::Edit::Batch { edits }).unwrap();
        let v = view_of(&p, 0);
        let c = v.clips.iter().find(|c| c.id == id).unwrap();
        assert!((c.transform.opacity - 40.0).abs() < 0.01);
        assert!((c.grade.exposure - 20.0).abs() < 0.01);
        h.undo(&mut p).unwrap();
        let v = view_of(&p, 0);
        assert_eq!(v.clips.iter().find(|c| c.id == id).unwrap().transform.opacity, 100.0);
    }
}
